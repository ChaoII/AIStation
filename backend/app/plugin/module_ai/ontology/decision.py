async def ensure_decision_object_type() -> dict:
    """把「决策」注册为本体的对象类型（幂等）。

    这样决策就能出现在对象探索里、可被关系引用、可被 Agent 查询、
    也能挂函数与派生属性——即官方所说的"决策数据**在本体内**"。
    """
    exists = (await _svc._exec(
        "SELECT id FROM ai_ont_object WHERE code='decision'", {})).fetchone()
    backing = (await _svc._exec("SELECT to_regclass('ai_ont_decision') AS t", {})).fetchone()
    if not backing or not backing[0]:
        return {"ok": False, "msg": "决策表尚未建立"}

    common = {
        "code": "decision", "name": "决策", "icon": "Flag",
        "key_prop": "code", "name_prop": "title",
        "desc": "组织的决策记录（决策数据：上下文 / 评估过的选项 / 下游影响）",
        "backing": "ai_ont_decision",
    }
    if exists:
        await _svc._exec_write(
            "UPDATE ai_ont_object SET name=:name, icon=:icon, key_prop=:key_prop, "
            "name_prop=:name_prop, description=:desc, backing_table=:backing, "
            "plural_name=CASE WHEN COALESCE(plural_name,'')='' THEN 'decisions' "
            "ELSE plural_name END WHERE code=:code", common)
        oid = int(exists[0])
    else:
        r = await _svc._exec_write(
            "INSERT INTO ai_ont_object(code,name,icon,key_prop,name_prop,description,"
            "backing_table,plural_name,api_name,status,visibility,enabled) "
            "VALUES (:code,:name,:icon,:key_prop,:name_prop,:desc,:backing,'decisions',"
            "'decisions','experimental','normal',true) RETURNING id", common)
        oid = int(r.scalar() or 0)

    created = 0
    for code, name, base, is_title in DECISION_PROPS:
        prop_code = f"decision_{code}"
        have = (await _svc._exec(
            "SELECT id FROM ai_ont_property WHERE object_code='decision' AND code=:c",
            {"c": prop_code})).fetchone()
        if have:
            continue
        await _svc._exec_write(
            "INSERT INTO ai_ont_property(object_code,code,name,prop_type,base_type,"
            "api_name,description,title_key,type_class,status,visibility) "
            "VALUES ('decision',:c,:n,:pt,:bt,:api,:d,:tk,'basic','experimental','normal')",
            {"c": prop_code, "n": name, "pt": base, "bt": base,
             "api": prop_code, "d": f"决策的{name}", "tk": is_title})
        created += 1
    return {"ok": True, "object_id": oid, "properties_created": created,
            "msg": f"决策对象类型已就绪（新增 {created} 个属性）"}


#: 进程内只自动注册一次，避免每次列表都查一遍
_ot_ready = False


async def _ensure_ot_once() -> None:
    """首次访问决策时自动把「决策」注册为对象类型（失败不影响决策功能本身）。"""
    global _ot_ready
    if _ot_ready:
        return
    try:
        r = await ensure_decision_object_type()
        _ot_ready = bool(r.get("ok"))
    except Exception:  # noqa: BLE001
        _ot_ready = False
