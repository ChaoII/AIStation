"""决策数据与决策谱系。

对齐官方 `why-ontology` 的定义（引原文）：

- **决策数据（decision data）**：*"the data generated by end users and agents as decisions are
  being made. This 'decision data' contains the context surrounding a given decision,
  the different options evaluated, and the downstream implications of the committed choice."*
  → 我们落成三张表：`ai_ont_decision_evidence`（上下文）、`ai_ont_decision_option`（评估过的选项）、
  `ai_ont_decision_impact`（下游影响）。

- **决策谱系（decision lineage）**：*"The end-to-end 'decision lineage' of **when** a given
  decision was made, **atop which version of enterprise data**, and **through which
  application**, is automatically captured."*
  → 三要素分别落到 `made_at` / `data_version` + `data_snapshot` / `channel`，且**自动捕获**而非手填。

- *"each decision informing the next in a shared lineage"* → 决策之间可互为依据
  （evidence.kind = ``decision``），从而形成决策→决策的谱系链。

本模块只做决策自身的读写与谱系，**执行**复用动作层（P0 的七道闸），
所以决策执行天然带提交条件、规则、副作用与审计。
"""
