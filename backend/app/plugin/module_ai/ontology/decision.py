async def _current_version(object_code: str) -> int:
    """决策基于哪个版本的企业数据（取该对象类型已发布的最高版本）。"""
    if not object_code:
        return 0
    try:
        rows = await _svc.list_versions(object_code)
        versions = [int(v.get("version") or 0) for v in rows]
        return max(versions) if versions else 0
    except Exception:  # noqa: BLE001
        return 0


async def _check_object_action_match(object_code: str, action_code: str) -> None:
    """决策针对的对象类型必须与执行动作的目标对象类型一致。

    不一致时执行阶段的前后快照会取错对象，捕获到的"下游影响"就成了假的。
    """
    if not object_code or not action_code:
        return
    acts = await _svc.list_actions(None)
    act = next((a for a in acts if a.get("code") == action_code), None)
    if not act:
        raise CustomException(msg=f"执行动作 {action_code} 不存在")
    target = act.get("object_code") or ""
    if target and target != object_code:
        label = act.get("name") or action_code
        raise CustomException(
            msg=f"动作「{label}」作用于 {target}，与决策针对的 {object_code} 不一致；"
                "请改选匹配的动作，或把决策对象类型改成该动作的目标对象")


