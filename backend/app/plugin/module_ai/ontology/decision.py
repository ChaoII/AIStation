async def upsert_decision(data: dict, actor_id: int | None = None,
                          actor_name: str = "") -> dict:
    """新建或修改一条决策（含选项与依据的整表替换）。"""
    title = (data.get("title") or "").strip()
    if not title:
        raise CustomException(msg="决策标题必填")
    code = (data.get("code") or "").strip()
    if code and not _CODE_RE.match(code):
        raise CustomException(msg="决策编码只能含字母/数字/下划线/短横线")
    if not code:
        # 中文标题推不出 ASCII 片段，交给唯一编码器兜底（同秒多条也不撞）
        code = await _unique_code(derive_decision_code(title))
    status = data.get("status") or "proposed"
    if status not in ONT_DECISION_STATUS:
        raise CustomException(msg=f"决策状态非法：{status}")
    channel = data.get("channel") or "ontology"
    if channel not in ONT_DECISION_CHANNELS:
        raise CustomException(msg=f"决策入口非法：{channel}")

    # 决策谱系第二要素：基于哪个版本的企业数据。不显式给就取该对象类型的当前已发布版本
    dver = data.get("data_version")
    if not dver:
        dver = await _current_version(data.get("object_code") or "")

    # 对象与动作必须指向同一个对象类型：
    # 否则执行时"前后快照"会取错对象，捕获到的下游影响就是假的。
    await _check_object_action_match(data.get("object_code") or "",
                                     data.get("action_code") or "")

    common = {
        "c": code, "t": title, "d": data.get("description", ""), "st": status,
        "cg": data.get("category", ""),
        "oc": data.get("object_code", ""), "ok": str(data.get("object_key", "")),
        "ac": data.get("action_code", ""),
        "p": _j(data.get("params") or {}),
        "ra": data.get("rationale", ""), "dv": int(dver or 0),
        "ds": _j(data.get("data_snapshot") or {}),
        "ch": channel,
        "mb": data.get("made_by") or actor_name or "",
        "db": data.get("decided_by") or "", "dn": data.get("decision_note", ""),
        "ei": _j(data.get("expected_impact") or {}),
        "oc2": data.get("outcome") or {},
        "sb": data.get("superseded_by", ""),
        "tg": _j(data.get("tags") or []),
    }
    if data.get("id"):
        await _svc._exec_write(
            "UPDATE ai_ont_decision SET title=:t, description=:d, status=:st, category=:cg, "
            "object_code=:oc, object_key=:ok, action_code=:ac, params=:p, rationale=:ra, "
            "data_version=:dv, data_snapshot=:ds, channel=:ch, made_by=:mb, "
            "decided_by=:db, decision_note=:dn, expected_impact=:ei, superseded_by=:sb, "
            "tags=:tg, updated_time=now() WHERE id=:id", {**common, "id": data["id"]})
        did = int(data["id"])
    else:
        r = await _svc._exec_write(
            "INSERT INTO ai_ont_decision(code,title,description,status,category,object_code,"
            "object_key,action_code,params,rationale,data_version,data_snapshot,channel,"
            "made_by,decided_by,decision_note,expected_impact,superseded_by,tags) "
            "VALUES (:c,:t,:d,:st,:cg,:oc,:ok,:ac,:p,:ra,:dv,:ds,:ch,:mb,:db,:dn,:ei,:sb,:tg) "
            "RETURNING id", common)
        did = int(r.scalar() or 0)

    if "options" in data:
        await _replace_options(code, data.get("options") or [])
    if "evidence" in data:
        await _replace_evidence(code, data.get("evidence") or [])

    await _svc._log_change(data.get("object_code", ""), "decision",
                           "save" if not data.get("id") else "update", f"决策 {title}")
    return {"ok": True, "id": did, "code": code,
            "msg": f"决策「{title}」已保存",
            "auto_data_version": int(dver or 0)}


async def _replace_options(code: str, options: list) -> None:
    await _svc._exec_write("DELETE FROM ai_ont_decision_option WHERE decision_code=:c",
                           {"c": code})
    for i, o in enumerate(options):
        if not isinstance(o, dict):
            continue
        await _svc._exec_write(
            "INSERT INTO ai_ont_decision_option(decision_code,code,label,description,params,"
            "score,projected_impact,chosen,reject_reason) "
            "VALUES (:dc,:c,:l,:d,:p,:s,:pi,:ch,:rr)",
            {"dc": code, "c": o.get("code") or f"opt{i + 1}",
             "l": o.get("label", ""), "d": o.get("description", ""),
             "p": _j(o.get("params") or {}),
             "s": o.get("score"), "pi": json.dumps(o.get("projected_impact") or {},
                                                   ensure_ascii=False),
             "ch": bool(o.get("chosen")), "rr": o.get("reject_reason", "")})


async def _replace_evidence(code: str, items: list) -> None:
    await _svc._exec_write("DELETE FROM ai_ont_decision_evidence WHERE decision_code=:c",
                           {"c": code})
    for e in items:
        if not isinstance(e, dict):
            continue
        kind = str(e.get("kind") or "manual")
        if kind not in ONT_EVIDENCE_KINDS:
            kind = "manual"
        await _svc._exec_write(
            "INSERT INTO ai_ont_decision_evidence(decision_code,kind,ref,label,value) "
            "VALUES (:dc,:k,:r,:l,:v)",
            {"dc": code, "k": kind, "r": str(e.get("ref", ""))[:240],
             "l": str(e.get("label", ""))[:240],
             "v": _j(e.get("value") or {})})


async def add_impact(code: str, kind: str, ref: str, label: str = "",
                     before: dict | None = None, after: dict | None = None,
                     note: str = "", auto: bool = False) -> None:
    if kind not in ONT_IMPACT_KINDS:
        kind = "external"
    await _svc._exec_write(
        "INSERT INTO ai_ont_decision_impact(decision_code,kind,ref,label,before,after,note,auto) "
        "VALUES (:dc,:k,:r,:l,:b,:a,:n,:au)",
        {"dc": code, "k": kind, "r": str(ref)[:240], "l": str(label)[:240],
         "b": _j(before or {}),
         "a": _j(after or {}),
         "n": note, "au": auto})


async def remove_decision(code: str, actor_id: int | None = None) -> dict:
    row = (await _svc._exec("SELECT title FROM ai_ont_decision WHERE code=:c AND is_deleted=false",
                            {"c": code})).fetchone()
    if not row:
        return {"ok": False, "msg": "决策不存在"}
    # 被后续决策当作依据引用时不允许删除（谱系会断）
    refs = (await _svc._exec(
        "SELECT DISTINCT decision_code FROM ai_ont_decision_evidence "
        "WHERE kind='decision' AND ref=:c", {"c": code})).fetchall()
    if refs:
        users = "、".join(x[0] for x in refs[:5])
        return {"ok": False, "msg": f"该决策被 {len(refs)} 条后续决策引用为依据（{users}），无法删除"}
    await _svc._exec_write("UPDATE ai_ont_decision SET is_deleted=true WHERE code=:c", {"c": code})
    for t in ("ai_ont_decision_option", "ai_ont_decision_evidence", "ai_ont_decision_impact"):
        await _svc._exec_write(f"DELETE FROM {t} WHERE decision_code=:c", {"c": code})
    return {"ok": True, "msg": f"决策「{row[0]}」已删除"}


async def decide(code: str, approve: bool, note: str = "",
                 actor_id: int | None = None, actor_name: str = "") -> dict:
    """拍板：批准或否决。只有 proposed 状态可拍板。"""
    d = await get_decision(code)
    if not d:
        return {"ok": False, "msg": "决策不存在"}
    if d["status"] != "proposed":
        return {"ok": False,
                "msg": f"当前状态为「{d['status_label']}」，只有待决状态可以拍板"}
    status = "approved" if approve else "rejected"
    await _svc._exec_write(
        "UPDATE ai_ont_decision SET status=:s, decided_by=:by, decided_at=now(), "
        "decision_note=:n, updated_time=now() WHERE code=:c",
        {"s": status, "by": actor_name or str(actor_id or ""), "n": note, "c": code})
    await _svc._log_change(d["object_code"], "decision", status, f"决策 {d['title']}")
    return {"ok": True, "status": status,
            "msg": f"已{'批准' if approve else '否决'}：{d['title']}"}


async def execute_decision(code: str, actor_id: int | None = None, actor_name: str = "",
                           approve: bool = False, principal: Any = None) -> dict:
    """执行决策：走动作层的七道闸，并**自动捕获下游影响**。

    这是决策谱系的"下游"来源——不是手填，而是执行前后对目标对象做差。
    """
    d = await get_decision(code)
    if not d:
        return {"ok": False, "msg": "决策不存在"}
    if d["status"] not in ("approved", "proposed"):
        return {"ok": False, "msg": f"当前状态为「{d['status_label']}」，不可执行"}
    if not d["action_code"]:
        return {"ok": False, "msg": "该决策未指定执行动作"}
    if d["status"] == "proposed":
        return {"ok": False, "msg": "决策尚未批准，请先拍板"}

    # 执行前快照（用于算下游影响）
    before = await get_object_props(d["object_code"], d["object_key"])

    # P4：决策执行同样要过权限门控（否则决策会成为绕过权限的旁路）
    if principal is None and actor_id:
        from . import security as _sec

        principal = await _sec.load_principal(actor_id)
    r = await _svc.execute_ontology_action(
        d["action_code"], str(d["object_key"]), dict(d["params"] or {}),
        actor_name, approve=approve, user_id=actor_id, principal=principal)
    if not r.get("ok"):
        await _svc._log_change(d["object_code"], "decision", "execute_failed",
                               f"决策 {d['title']}：{r.get('msg')}")
        return {"ok": False, "msg": r.get("msg"), "needs_approval": r.get("needs_approval"),
                "action_result": r}

    after = await get_object_props(d["object_code"], d["object_key"])
    # 自动登记下游影响：对象哪些字段变了
    changed = {k: {"before": before.get(k), "after": after.get(k)}
               for k in set(before) | set(after)
               if before.get(k) != after.get(k)}
    if changed:
        await add_impact(
            code, "object_changed", f"{d['object_code']}:{d['object_key']}",
            f"{d['object_code']} 被 {d['action_code']} 修改",
            before={k: v["before"] for k, v in changed.items()},
            after={k: v["after"] for k, v in changed.items()},
            note=f"由动作 {d['action_code']} 自动改动的字段：" + "、".join(sorted(changed)),
            auto=True)
    elif r.get("rows"):
        await add_impact(code, "object_changed", f"{d['object_code']}:{d['object_key']}",
                         f"{d['object_code']} 执行了 {d['action_code']}",
                         before=before, after=after, note="执行成功但字段值无变化", auto=True)

    # 回填 execution_id：取刚写下的回写审计 id（走 catalog 接口，本体不直读问数的表）
    from app.plugin.module_ai import catalog

    eid = await catalog.last_writeback_id()

    await _svc._exec_write(
        "UPDATE ai_ont_decision SET status='executed', executed_at=now(), execution_id=:e, "
        "updated_time=now() WHERE code=:c", {"e": eid, "c": code})
    await _svc._log_change(d["object_code"], "decision", "execute",
                           f"决策 {d['title']} 已执行（影响 {len(changed)} 个字段）")
    return {"ok": True, "rows": r.get("rows", 0), "execution_id": eid,
            "changed": changed, "impacts_recorded": 1 if changed else 0,
            "side_effects": r.get("side_effects", []),
            "msg": f"决策已执行，捕获到 {len(changed)} 个字段变化"}


async def record_outcome(code: str, outcome: dict, actor_name: str = "") -> dict:
    """记录事后结果（决策的实际效果）。"""
    d = await get_decision(code)
    if not d:
        return {"ok": False, "msg": "决策不存在"}
    payload = dict(outcome or {})
    payload.setdefault("recorded_at", _now())
    payload.setdefault("recorded_by", actor_name)
    await _svc._exec_write(
        "UPDATE ai_ont_decision SET outcome=:o, updated_time=now() WHERE code=:c",
        {"o": _j(payload), "c": code})
    if payload.get("metric") is not None or payload.get("actual") is not None:
        await add_impact(code, "metric", str(payload.get("metric") or "outcome"),
                         "事后指标", before={"expected": payload.get("expected")},
                         after={"actual": payload.get("actual")},
                         note=payload.get("note", ""))
    return {"ok": True, "msg": "已记录事后结果"}


