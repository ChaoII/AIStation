async def decision_lineage(code: str, depth: int = 3) -> dict:
    """一条决策的完整谱系：上游依据 + 下游影响，可递归。

    上游 = 该决策引用的对象/函数/版本/外部数据/**上游决策**；
    下游 = 执行造成的影响 + **把本决策当作依据的后续决策**。
    """
    root = await get_decision(code)
    if not root:
        return {"ok": False, "msg": "决策不存在"}
    depth = max(1, min(int(depth or 3), 5))

    async def _walk(cur_code: str, level: int, seen: set) -> dict:
        cur = await get_decision(cur_code)
        if not cur:
            return {}
        node = {
            "code": cur["code"], "title": cur["title"], "status": cur["status"],
            "status_label": cur["status_label"], "made_at": cur["made_at"],
            "made_by": cur["made_by"], "data_version": cur["data_version"],
            "channel": cur["channel"], "rationale": cur["rationale"],
            "evidence": cur["evidence"], "impacts": cur["impacts"],
            "upstream": [], "downstream": [],
        }
        if level >= depth:
            return node
        # 上游：被本决策引用为依据的决策
        for e in cur["evidence"]:
            if e["kind"] == "decision" and e["ref"] and e["ref"] not in seen:
                seen.add(e["ref"])
                child = await _walk(e["ref"], level + 1, seen)
                if child:
                    node["upstream"].append(child)
        # 下游：把本决策当作依据的决策
        r = await _svc._exec(
            "SELECT DISTINCT decision_code FROM ai_ont_decision_evidence "
            "WHERE kind='decision' AND ref=:c", {"c": cur_code})
        for (dc,) in r.fetchall():
            if dc and dc not in seen:
                seen.add(dc)
                child = await _walk(dc, level + 1, seen)
                if child:
                    node["downstream"].append(child)
        return node

    tree = await _walk(code, 1, {code})
    return {"ok": True, "root": code, "depth": depth, "lineage": tree,
            "summary": _lineage_summary(tree)}


def _lineage_summary(node: dict) -> dict:
    """谱系统计：多少依据、多少影响、向上/向下各多少层决策。"""
    up = down = 0
    stack = [node]
    while stack:
        n = stack.pop()
        up += len(n.get("upstream") or [])
        down += len(n.get("downstream") or [])
        stack.extend(n.get("upstream") or [])
        stack.extend(n.get("downstream") or [])
    return {"evidence": len(node.get("evidence") or []),
            "impacts": len(node.get("impacts") or []),
            "upstream_decisions": up, "downstream_decisions": down}


async def decision_graph(status: str | None = None, limit: int = 60) -> dict:
    """决策谱系图：节点=决策/对象，边=依据与影响。供前端 GraphCanvas 渲染。"""
    decisions = await list_decisions(status=status, limit=limit)
    codes = {d["code"] for d in decisions}
    nodes: list[dict] = []
    edges: list[dict] = []
    seen_obj: set[str] = set()
    for d in decisions:
        nodes.append({"id": d["code"], "name": d["title"], "etype": "decision",
                      "weight": 6, "status": d["status"]})
        if d["object_code"]:
            oid = f"obj:{d['object_code']}:{d['object_key']}"
            if oid not in seen_obj:
                seen_obj.add(oid)
                nodes.append({"id": oid, "name": f"{d['object_code']}#{d['object_key']}",
                              "etype": "object", "weight": 4})
            edges.append({"source": d["code"], "target": oid, "rtype": "关于", "weight": 1})
        for e in await list_evidence(d["code"]):
            if e["kind"] == "decision" and e["ref"] in codes:
                edges.append({"source": e["ref"], "target": d["code"],
                              "rtype": "为依据", "weight": 2})
            elif e["kind"] == "object" and e["ref"]:
                oid = f"ev:{e['ref']}"
                if oid not in seen_obj:
                    seen_obj.add(oid)
                    nodes.append({"id": oid, "name": e["label"] or e["ref"],
                                  "etype": "evidence", "weight": 3})
                edges.append({"source": oid, "target": d["code"],
                              "rtype": "依据", "weight": 1})
        for im in await list_impacts(d["code"]):
            if im["kind"] == "decision" and im["ref"] in codes:
                edges.append({"source": d["code"], "target": im["ref"],
                              "rtype": "引发", "weight": 2})
    return {"ok": True, "nodes": nodes, "edges": edges,
            "counts": {"decisions": len(decisions), "nodes": len(nodes), "edges": len(edges)}}


async def decision_stats() -> dict:
    """决策统计：按状态/类别/入口/时间分布。"""
    by_status: dict[str, int] = {}
    r = await _svc._exec("SELECT COALESCE(status,'proposed'), count(*) FROM ai_ont_decision "
                         "WHERE is_deleted=false GROUP BY 1")
    for s, n in r.fetchall():
        by_status[s] = int(n)
    by_channel: dict[str, int] = {}
    r2 = await _svc._exec("SELECT COALESCE(channel,'ontology'), count(*) FROM ai_ont_decision "
                          "WHERE is_deleted=false GROUP BY 1")
    for c, n in r2.fetchall():
        by_channel[ONT_CHANNEL_LABEL.get(c, c)] = int(n)
    top_objects: list[dict] = []
    r3 = await _svc._exec(
        "SELECT object_code, count(*) AS n FROM ai_ont_decision "
        "WHERE is_deleted=false AND COALESCE(object_code,'')<>'' "
        "GROUP BY 1 ORDER BY n DESC LIMIT 10")
    for oc, n in r3.fetchall():
        top_objects.append({"object_code": oc, "count": int(n)})
    r4 = await _svc._exec(
        "SELECT COALESCE(made_by,'(未记录)'), count(*) FROM ai_ont_decision "
        "WHERE is_deleted=false GROUP BY 1 ORDER BY 2 DESC LIMIT 10")
    by_person = [{"made_by": m, "count": int(n)} for m, n in r4.fetchall()]
    total = sum(by_status.values())
    decided = sum(v for k, v in by_status.items() if k != "proposed")
    executed = by_status.get("executed", 0)
    return {
        "total": total,
        "by_status": by_status,
        "by_status_label": {ONT_DECISION_STATUS_LABEL.get(k, k): v
                            for k, v in by_status.items()},
        "by_channel": by_channel,
        "top_objects": top_objects,
        "by_person": by_person,
        "decided_rate": round(decided * 100 / total, 1) if total else 0.0,
        "executed_rate": round(executed * 100 / total, 1) if total else 0.0,
        "pending": by_status.get("proposed", 0),
    }


