_CODE_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_\-]{0,118}$")


def _j(v: Any) -> str:
    """安全 JSON 序列化。

    决策依据/影响里存的是**对象属性的快照**，里面有 datetime、Decimal 等类型，
    直接 json.dumps 会抛 TypeError —— 快照绝不能因为类型而失败。
    """
    def _default(o: Any) -> Any:
        if isinstance(o, datetime):
            return o.strftime("%Y-%m-%d %H:%M:%S")
        if isinstance(o, Decimal):
            return float(o)
        if isinstance(o, (bytes, bytearray)):
            return o.decode("utf-8", "replace")
        return str(o)

    return json.dumps(v, ensure_ascii=False, default=_default)


def _now() -> str:
    return datetime.now().strftime("%Y-%m-%d %H:%M:%S")


def derive_decision_code(title: str) -> str:
    """由标题推导一个可读的决策编码。

    中文标题推不出 ASCII 片段，此时用标题摘要 + 时间戳做基底；
    **最终唯一性由 ``_unique_code`` 保证**（同秒建多条也不能撞唯一约束）。
    """
    ascii_part = re.sub(r"[^A-Za-z0-9]+", "_", title or "").strip("_").lower()
    if ascii_part:
        return f"dec_{ascii_part[:40]}"
    digest = hashlib.md5((title or "").encode("utf-8")).hexdigest()[:8]
    return f"dec_{digest}_{datetime.now().strftime('%H%M%S')}"


async def _unique_code(base: str) -> str:
    """确保编码唯一：被占用就追加 ``_2``/``_3``…

    注意唯一约束**不区分软删除**，所以查的时候也不能带 ``is_deleted`` 条件。
    """
    code = base[:110]
    n = 1
    while True:
        row = (await _svc._exec("SELECT 1 FROM ai_ont_decision WHERE code=:c",
                                {"c": code})).fetchone()
        if not row:
            return code
        n += 1
        suffix = f"_{n}"
        code = base[: 110 - len(suffix)] + suffix


