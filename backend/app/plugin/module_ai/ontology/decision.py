_DEC_COLS = (
    "SELECT id,code,title,COALESCE(description,''),COALESCE(status,'proposed'),"
    "COALESCE(category,''),COALESCE(object_code,''),COALESCE(object_key,''),"
    "COALESCE(action_code,''),params,COALESCE(rationale,''),"
    "COALESCE(data_version,0),data_snapshot,COALESCE(channel,'ontology'),"
    "COALESCE(made_by,''),made_at,COALESCE(decided_by,''),decided_at,"
    "COALESCE(decision_note,''),executed_at,COALESCE(execution_id,0),"
    "expected_impact,outcome,COALESCE(superseded_by,''),tags,created_time "
    "FROM ai_ont_decision "
)
_DEC_FIELDS = (
    "id", "code", "title", "description", "status", "category",
    "object_code", "object_key", "action_code", "params", "rationale",
    "data_version", "data_snapshot", "channel", "made_by", "made_at",
    "decided_by", "decided_at", "decision_note", "executed_at", "execution_id",
    "expected_impact", "outcome", "superseded_by", "tags", "created_time",
)
_JSON_FIELDS = ("params", "data_snapshot", "expected_impact", "outcome", "tags")


def _row_to_decision(row) -> dict:
    out: dict[str, Any] = {}
    for i, name in enumerate(_DEC_FIELDS):
        v = row[i]
        if name in _JSON_FIELDS:
            v = _svc._json_list(v) if name == "tags" else _svc._json_dict(v)
        elif isinstance(v, datetime):
            v = v.strftime("%Y-%m-%d %H:%M:%S")
        out[name] = v
    out["status_label"] = ONT_DECISION_STATUS_LABEL.get(out["status"], out["status"])
    out["channel_label"] = ONT_CHANNEL_LABEL.get(out["channel"], out["channel"])
    return out


async def list_decisions(status: str | None = None, object_code: str | None = None,
                         made_by: str | None = None, category: str | None = None,
                         keyword: str | None = None, limit: int = 200) -> list[dict]:
    await _ensure_ot_once()
    sql = _DEC_COLS + "WHERE is_deleted=false"
    params: dict = {}
    if status:
        sql += " AND status=:st"
        params["st"] = status
    if object_code:
        sql += " AND object_code=:oc"
        params["oc"] = object_code
    if made_by:
        sql += " AND made_by=:mb"
        params["mb"] = made_by
    if category:
        sql += " AND category=:cg"
        params["cg"] = category
    if keyword:
        sql += (f" AND (title {_svc._ilike()} :kw OR code {_svc._ilike()} :kw "
            f"OR rationale {_svc._ilike()} :kw)")
        params["kw"] = f"%{keyword}%"
    sql += f" ORDER BY id DESC LIMIT {max(1, min(int(limit or 200), 1000))}"
    rows = (await _svc._exec(sql, params)).fetchall()
    out = [_row_to_decision(r) for r in rows]
    # 附带选项数/依据数/影响数，列表页可直接展示
    if out:
        codes = [d["code"] for d in out]
        counts = await _counts(codes)
        for d in out:
            c = counts.get(d["code"], {})
            d["option_count"] = c.get("options", 0)
            d["evidence_count"] = c.get("evidence", 0)
            d["impact_count"] = c.get("impact", 0)
    return out


async def _counts(codes: list[str]) -> dict:
    """一次查出多个决策的选项/依据/影响条数，避免 N+1。"""
    out: dict[str, dict] = {}
    for table, key in (("ai_ont_decision_option", "options"),
                       ("ai_ont_decision_evidence", "evidence"),
                       ("ai_ont_decision_impact", "impact")):
        r = await _svc._exec(
            f"SELECT decision_code, count(*) FROM {table} "
            "WHERE decision_code = ANY(:codes) GROUP BY decision_code",
            {"codes": codes})
        for dc, n in r.fetchall():
            out.setdefault(dc, {})[key] = int(n or 0)
    return out


async def get_decision(code: str) -> dict | None:
    r = await _svc._exec(_DEC_COLS + "WHERE code=:c AND is_deleted=false", {"c": code})
    row = r.fetchone()
    if not row:
        return None
    d = _row_to_decision(row)
    d["options"] = await list_options(code)
    d["evidence"] = await list_evidence(code)
    d["impacts"] = await list_impacts(code)
    return d


async def list_options(code: str) -> list[dict]:
    r = await _svc._exec(
        "SELECT id,COALESCE(code,''),COALESCE(label,''),COALESCE(description,''),params,"
        "score,projected_impact,chosen,COALESCE(reject_reason,'') "
        "FROM ai_ont_decision_option WHERE decision_code=:c ORDER BY id", {"c": code})
    return [{"id": x[0], "code": x[1], "label": x[2], "description": x[3],
             "params": _svc._json_dict(x[4]), "score": float(x[5]) if x[5] is not None else None,
             "projected_impact": _svc._json_dict(x[6]), "chosen": bool(x[7]),
             "reject_reason": x[8]} for x in r.fetchall()]


async def list_evidence(code: str) -> list[dict]:
    r = await _svc._exec(
        "SELECT id,COALESCE(kind,'object'),COALESCE(ref,''),COALESCE(label,''),value,created_time "
        "FROM ai_ont_decision_evidence WHERE decision_code=:c ORDER BY id", {"c": code})
    return [{"id": x[0], "kind": x[1], "kind_label": ONT_EVIDENCE_LABEL.get(x[1], x[1]),
             "ref": x[2], "label": x[3], "value": _svc._json_dict(x[4]),
             "created_time": x[5].strftime("%Y-%m-%d %H:%M:%S") if x[5] else ""}
            for x in r.fetchall()]


async def list_impacts(code: str) -> list[dict]:
    r = await _svc._exec(
        "SELECT id,COALESCE(kind,'object_changed'),COALESCE(ref,''),COALESCE(label,''),"
        "before,after,COALESCE(note,''),auto,created_time "
        "FROM ai_ont_decision_impact WHERE decision_code=:c ORDER BY id", {"c": code})
    return [{"id": x[0], "kind": x[1], "kind_label": ONT_IMPACT_LABEL.get(x[1], x[1]),
             "ref": x[2], "label": x[3], "before": _svc._json_dict(x[4]),
             "after": _svc._json_dict(x[5]), "note": x[6], "auto": bool(x[7]),
             "created_time": x[8].strftime("%Y-%m-%d %H:%M:%S") if x[8] else ""}
            for x in r.fetchall()]


