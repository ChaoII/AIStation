_SC_COLS = (
    "SELECT id,code,COALESCE(name,''),COALESCE(description,''),COALESCE(status,'active'),"
    "COALESCE(base_version,0),COALESCE(merge_action_code,''),scope,"
    "COALESCE(created_by,''),created_time,expires_at,applied_at,COALESCE(applied_by,''),"
    "COALESCE(edit_count,0),action_codes,is_persisted,COALESCE(scenario_object_key,'') "
    "FROM ai_ont_scenario "
)
_SC_FIELDS = ("id", "code", "name", "description", "status", "base_version",
              "merge_action_code", "scope", "created_by", "created_time", "expires_at",
              "applied_at", "applied_by", "edit_count", "action_codes", "is_persisted",
              "scenario_object_key")


def _row_to_scenario(row) -> dict:
    out: dict[str, Any] = {}
    for i, name in enumerate(_SC_FIELDS):
        v = row[i]
        if name in ("scope",):
            v = _svc._json_dict(v)
        elif name == "action_codes":
            v = _svc._json_list(v)
        elif isinstance(v, datetime):
            v = v.strftime("%Y-%m-%d %H:%M:%S")
        out[name] = v
    out["status_label"] = ONT_SCENARIO_STATUS_LABEL.get(out["status"], out["status"])
    out["is_expired"] = bool(
        out["status"] == "active" and out["expires_at"]
        and str(out["expires_at"]) < _now())
    out["edit_limit"] = MAX_EDITS
    out["action_limit"] = MAX_ACTIONS
    return out


async def list_scenarios(status: str | None = None, limit: int = 200) -> list[dict]:
    sql = _SC_COLS + "WHERE is_deleted=false"
    params: dict = {}
    if status:
        sql += " AND status=:st"
        params["st"] = status
    sql += f" ORDER BY id DESC LIMIT {max(1, min(int(limit or 200), 1000))}"
    out = [_row_to_scenario(r) for r in (await _svc._exec(sql, params)).fetchall()]
    for s in out:
        s["edit_count"] = await _count_edits(s["code"])
        s["object_count"] = len(await edited_objects(s["code"]))
    return out


async def get_scenario(code: str) -> dict | None:
    r = await _svc._exec(_SC_COLS + "WHERE code=:c AND is_deleted=false", {"c": code})
    row = r.fetchone()
    if not row:
        return None
    s = _row_to_scenario(row)
    s["edits"] = await list_edits(code)
    s["diff"] = await scenario_diff(code)
    return s


async def _count_edits(code: str) -> int:
    return int((await _svc._exec(
        "SELECT count(*) FROM ai_ont_scenario_edit WHERE scenario_code=:c",
        {"c": code})).scalar() or 0)


async def list_edits(code: str) -> list[dict]:
    r = await _svc._exec(
        "SELECT id,object_code,COALESCE(object_key,''),COALESCE(kind,'modify'),before,after,"
        "COALESCE(action_code,''),created_time FROM ai_ont_scenario_edit "
        "WHERE scenario_code=:c ORDER BY id", {"c": code})
    return [{"id": x[0], "object_code": x[1], "object_key": x[2], "kind": x[3],
             "kind_label": ONT_EDIT_LABEL.get(x[3], x[3]),
             "before": _svc._json_dict(x[4]), "after": _svc._json_dict(x[5]),
             "action_code": x[6],
             "created_time": x[7].strftime("%Y-%m-%d %H:%M:%S") if x[7] else ""}
            for x in r.fetchall()]


async def edited_objects(code: str) -> list[dict]:
    """场景里被编辑过的对象（按对象聚合，供 diff 与对比用）。"""
    r = await _svc._exec(
        "SELECT object_code, COALESCE(object_key,''), count(*) FROM ai_ont_scenario_edit "
        "WHERE scenario_code=:c GROUP BY 1,2 ORDER BY 1,2", {"c": code})
    return [{"object_code": x[0], "object_key": x[1], "edits": int(x[2])}
            for x in r.fetchall()]


async def scenario_diff(code: str) -> dict:
    """场景相对基线的差异：每个对象最终会变成什么样。

    把同一对象的多次编辑按顺序叠加，得到「基线 → 最终」的净变化。
    删除的对象单独列出；模型预测结果单独列出（官方：不会合并）。
    """
    sc = (await _svc._exec("SELECT 1 FROM ai_ont_scenario WHERE code=:c AND is_deleted=false",
                           {"c": code})).fetchone()
    if not sc:
        return {"ok": False, "msg": "场景不存在"}
    edits = await list_edits(code)
    per: dict[tuple[str, str], dict] = {}
    model_results: list[dict] = []
    for e in edits:
        if e["kind"] == "model_result":
            model_results.append(e)
            continue
        k = (e["object_code"], e["object_key"])
        slot = per.setdefault(k, {
            "object_code": e["object_code"], "object_key": e["object_key"],
            "before": dict(e["before"]), "after": dict(e["after"]),
            "kinds": [], "actions": [],
        })
        # 第一次的 before 才是真正的基线
        if not slot["kinds"]:
            slot["before"] = dict(e["before"])
        slot["after"] = {**slot["after"], **(e["after"] or {})}
        if e["kind"] == "delete":
            slot["after"] = {}
            slot["deleted"] = True
        slot["kinds"].append(e["kind"])
        if e["action_code"] and e["action_code"] not in slot["actions"]:
            slot["actions"].append(e["action_code"])
    changes = []
    for slot in per.values():
        changed = {k: {"before": slot["before"].get(k), "after": slot["after"].get(k)}
                   for k in set(slot["before"]) | set(slot["after"])
                   if slot["before"].get(k) != slot["after"].get(k)}
        slot["changed"] = changed
        slot["kind_label"] = "、".join(sorted({ONT_EDIT_LABEL.get(k, k)
                                               for k in slot["kinds"]}))
        changes.append(slot)
    changes.sort(key=lambda x: (x["object_code"], x["object_key"]))
    return {"ok": True, "scenario": code,
            "objects_changed": len(changes), "edits": len(edits),
            "changes": changes,
            "model_results": model_results,
            "model_result_note": "模型预测结果不会在合并时写入本体（官方语义）"}


