# ---------------------------------------------------------------------------
async def compare_scenarios(codes: list[str]) -> dict:
    """并排对比多个场景：同一对象在不同场景下会变成什么样。"""
    codes = [c for c in (codes or []) if c][:6]
    if len(codes) < 2:
        return {"ok": False, "msg": "至少选择 2 个场景才能对比"}
    metas = []
    for c in codes:
        sc = await get_scenario(c)
        if not sc:
            return {"ok": False, "msg": f"场景 {c} 不存在"}
        metas.append(sc)
    # 收集所有被任一场景编辑过的对象
    keys: set[tuple[str, str]] = set()
    per: dict[str, dict] = {}
    for c in codes:
        d = await scenario_diff(c)
        per[c] = {(x["object_code"], x["object_key"]): x for x in d["changes"]}
        keys |= set(per[c].keys())
    rows = []
    for oc, ok_ in sorted(keys):
        row = {"object_code": oc, "object_key": ok_, "scenarios": {}}
        for c in codes:
            ch = per[c].get((oc, ok_))
            row["scenarios"][c] = ({"changed": ch["changed"],
                                    "kind_label": ch["kind_label"]}
                                   if ch else None)
        rows.append(row)
    return {"ok": True, "scenarios": [
        {"code": m["code"], "name": m["name"], "status": m["status_label"],
         "edits": m["edit_count"]} for m in metas],
        "rows": rows, "object_count": len(rows),
        "msg": f"{len(rows)} 个对象在 {len(codes)} 个场景下的差异"}
