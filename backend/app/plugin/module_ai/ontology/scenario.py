async def create_scenario(data: dict, actor_name: str = "") -> dict:
    name = (data.get("name") or "").strip()
    if not name:
        raise CustomException(msg="场景名称必填")
    code = (data.get("code") or "").strip() or await _unique_code(name)
    ttl = int(data.get("ttl_days") or DEFAULT_TTL_DAYS)
    ttl = max(1, min(ttl, 365))
    # 注意：expires_at 是 TIMESTAMP 列，必须传 datetime 对象（传字符串 asyncpg 会拒绝）
    expires_dt = datetime.now() + timedelta(days=ttl)
    expires = expires_dt.strftime("%Y-%m-%d %H:%M:%S")
    scope = data.get("scope") or {}
    params = {
        "c": code, "n": name, "d": data.get("description", ""),
        "bv": int(data.get("base_version") or 0),
        "ma": data.get("merge_action_code", ""),
        "sp": _j(scope),
        "cb": data.get("created_by") or actor_name or "",
        "ex": expires_dt,
    }
    await _svc._exec_write(
        "INSERT INTO ai_ont_scenario(code,name,description,base_version,merge_action_code,"
        "scope,created_by,expires_at) VALUES (:c,:n,:d,:bv,:ma,:sp,:cb,:ex)", params)
    await _svc._log_change("", "scenario", "create", f"场景 {name}（{code}）")
    return {"ok": True, "code": code, "expires_at": expires,
            "msg": f"场景「{name}」已创建（{ttl} 天后自动过期）"}


async def _unique_code(name: str) -> str:
    import hashlib
    import re

    ascii_part = re.sub(r"[^A-Za-z0-9]+", "_", name or "").strip("_").lower()
    base = f"sc_{ascii_part[:40]}" if ascii_part else \
        f"sc_{hashlib.md5((name or '').encode()).hexdigest()[:8]}_{datetime.now():%H%M%S}"
    code, n = base[:110], 1
    while (await _svc._exec("SELECT 1 FROM ai_ont_scenario WHERE code=:c",
                            {"c": code})).fetchone():
        n += 1
        code = base[: 110 - len(f"_{n}")] + f"_{n}"
    return code


async def update_scenario(code: str, data: dict) -> dict:
    sc = await get_scenario(code)
    if not sc:
        raise CustomException(msg="场景不存在")
    if sc["status"] != "active":
        raise CustomException(msg=f"场景状态为「{sc['status_label']}」，不能再改配置")
    await _svc._exec_write(
        "UPDATE ai_ont_scenario SET name=:n, description=:d, merge_action_code=:ma, "
        "scope=:sp WHERE code=:c",
        {"n": data.get("name") or sc["name"], "d": data.get("description", sc["description"]),
         "ma": data.get("merge_action_code", sc["merge_action_code"]),
         "sp": _j(data.get("scope") or sc["scope"]), "c": code})
    return {"ok": True, "msg": "场景配置已更新"}


async def _check_active(code: str) -> dict:
    sc = await get_scenario(code)
    if not sc:
        raise CustomException(msg=f"场景 {code} 不存在")
    if sc["status"] != "active":
        raise CustomException(msg=f"场景状态为「{sc['status_label']}」，不可再编辑")
    if sc["is_expired"]:
        await _svc._exec_write(
            "UPDATE ai_ont_scenario SET status='expired' WHERE code=:c", {"c": code})
        raise CustomException(msg="场景已过期（默认寿命 31 天）")
    return sc


async def in_scope(scenario_code: str, object_code: str) -> tuple[bool, str]:
    """对象类型是否在场景允许编辑的范围内。

    官方：创建合并动作时要先划定场景编辑的范围（Object types / Link types）。
    范围为空 = 不限制。
    """
    sc = (await _svc._exec("SELECT scope FROM ai_ont_scenario WHERE code=:c",
                           {"c": scenario_code})).fetchone()
    scope = _svc._json_dict(sc[0]) if sc else {}
    allowed = [str(x) for x in (scope.get("object_types") or [])]
    if not allowed:
        return True, "未限定范围"
    if object_code in allowed:
        return True, "在场景范围内"
    return False, f"对象类型 {object_code} 不在该场景的编辑范围内（范围：{'、'.join(allowed)}）"


async def record_edit(scenario_code: str, object_code: str, object_key: str, kind: str,
                      before: dict, after: dict, action_code: str = "") -> dict:
    """把一次编辑记入场景（而不是写真实表）。

    同时执行官方限额：≤30,000 处编辑、≤50 个动作、且在场景范围内。

    **本函数不抛异常**：它被动作执行路径调用，那条路径的约定是返回结果字典
    （抛出去会变成 500，而不是可读的拒绝原因）。
    """
    try:
        sc = await _check_active(scenario_code)
    except CustomException as e:
        return {"ok": False, "msg": getattr(e, "msg", None) or str(e)}
    ok_s, why_s = await in_scope(scenario_code, object_code)
    if not ok_s:
        return {"ok": False, "msg": why_s}
    if kind not in ONT_EDIT_KINDS:
        return {"ok": False, "msg": f"编辑种类不支持：{kind}"}

    n = await _count_edits(scenario_code)
    if n >= MAX_EDITS:
        return {"ok": False,
                "msg": f"该场景已达官方编辑上限（{MAX_EDITS} 处），请新建场景"}
    actions = list(sc.get("action_codes") or [])
    if action_code and action_code not in actions:
        if len(actions) >= MAX_ACTIONS:
            return {"ok": False,
                    "msg": f"该场景已达官方动作上限（{MAX_ACTIONS} 个），请新建场景"}
        actions.append(action_code)

    await _svc._exec_write(
        "INSERT INTO ai_ont_scenario_edit(scenario_code,object_code,object_key,kind,before,"
        "after,action_code) VALUES (:sc,:oc,:ok,:k,:b,:a,:ac)",
        {"sc": scenario_code, "oc": object_code, "ok": str(object_key), "k": kind,
         "b": _j(before or {}), "a": _j(after or {}), "ac": action_code})
    await _svc._exec_write(
        "UPDATE ai_ont_scenario SET edit_count=:n, action_codes=:ac WHERE code=:c",
        {"n": n + 1, "ac": _j(actions), "c": scenario_code})
    return {"ok": True, "edits": n + 1,
            "msg": f"已在场景内记录 1 处编辑（共 {n + 1} 处）"}


# ---------------------------------------------------------------------------
# 读叠加：基线数据 + 场景差异
# ---------------------------------------------------------------------------
async def overlay_edits(scenario_code: str, object_code: str,
                        items: list[dict]) -> list[dict]:
    """把场景内的编辑叠加到一批实例上。

    - 修改：合并 after 到 props
    - 创建：追加（基线里没有的对象）
    - 删除：从结果里移除
    """
    edits = [e for e in await list_edits(scenario_code) if e["object_code"] == object_code]
    if not edits:
        return items
    by_key: dict[str, dict] = {}
    created: dict[str, dict] = {}
    deleted: set[str] = set()
    for e in edits:
        k = str(e["object_key"])
        if e["kind"] == "delete":
            deleted.add(k)
        elif e["kind"] == "create":
            created[k] = dict(e["after"])
        elif e["kind"] == "modify":
            by_key.setdefault(k, {}).update(e["after"] or {})
    out: list[dict] = []
    seen: set[str] = set()
    for it in items:
        k = str(it.get("key"))
        if k in deleted:
            continue
        seen.add(k)
        if k in by_key:
            it = dict(it)
            it["props"] = {**(it.get("props") or {}), **by_key[k]}
            it["scenario_edited"] = True
        out.append(it)
    for k, props in created.items():
        if k in deleted or k in seen:
            continue
        out.append({"key": k, "label": props.get("name") or k, "props": props,
                    "scenario_created": True})
    return out


async def overlay_instance(scenario_code: str, object_code: str, key: str,
                           props: dict) -> dict:
    """单条实例的叠加（返回叠加后的 props；被删除则返回 {}）。"""
    edits = [e for e in await list_edits(scenario_code) if e["object_code"] == object_code
             and str(e["object_key"]) == str(key)]
    if not edits:
        return props
    out = dict(props or {})
    for e in edits:
        if e["kind"] == "delete":
            return {}
        if e["kind"] in ("modify", "create"):
            out.update(e["after"] or {})
    return out


async def is_deleted_in_scenario(scenario_code: str, object_code: str, key: str) -> bool:
    r = (await _svc._exec(
        "SELECT 1 FROM ai_ont_scenario_edit WHERE scenario_code=:s AND object_code=:o "
        "AND object_key=:k AND kind='delete' LIMIT 1",
        {"s": scenario_code, "o": object_code, "k": str(key)})).fetchone()
    return bool(r)


