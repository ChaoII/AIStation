"""场景（Scenario）：本体数据的沙箱式"假设分析"。

对齐官方 `ontology/overview-ontology-scenario`（当前 Beta 版，非 legacy 的 Workshop 版）：

- *"A scenario is essentially a **sandbox to apply edits on top of the data in your Ontology**,
  generated by applying one or more actions."*
- 用途：what-if 分析、业务逻辑模拟、**智能体评估与预测**、多场景对比。
- *"Scenarios are **not data versioning tools**. They cannot provide a snapshot of your Ontology
  at a historical point in time."*
- **TTL**：默认 31 天后自动删除。
- **自动 rebase**：官方每 10 分钟把场景 rebase 到基线之上。
- **按执行上下文治理**：提交条件可区分"在场景内执行"与"对主本体执行"，
  于是可以给场景内更宽松的条件，而把「合并」单独用 merge action 的提交条件管住。
- **合并**：*"Scenarios are merged through action types ... commits all those staged edits to the
  Ontology as a **single transaction**"*；模型结果**不会**被合并。

**我们的实现方式与官方的一处关键差异（是更简单的等价物）**：
官方在底层复制一份数据并定期 rebase；我们把场景存成**相对基线的差异集（edit set）**，
读的时候叠加。这样**天然总是基于最新基线数据**——等价于官方的自动 rebase，
因此不需要定时任务，也不存在 rebase 冲突。
"""
from __future__ import annotations

import json
from datetime import datetime, timedelta
from typing import Any

from app.core.exceptions import CustomException

from . import service as _svc

# ---------------------------------------------------------------------------
# 常量（限额直接采用官方数字）
# ---------------------------------------------------------------------------
ONT_SCENARIO_STATUS = ("active", "applied", "discarded", "expired")
ONT_SCENARIO_STATUS_LABEL = {
    "active": "进行中", "applied": "已合并", "discarded": "已丢弃", "expired": "已过期",
}
#: 官方限制：单个场景最多 30,000 处编辑
MAX_EDITS = 30000
#: 官方限制：单个场景最多 50 个动作
MAX_ACTIONS = 50
#: 官方限制：场景内从对象集加载不超过 10,000 个对象
MAX_LOAD_OBJECTS = 10000
#: 官方：默认寿命 31 天
DEFAULT_TTL_DAYS = 31

#: 编辑种类（官方列举：修改属性 / 创建对象 / 删除对象 / 增加关系 / 删除关系）
ONT_EDIT_KINDS = ("modify", "create", "delete", "link_add", "link_remove", "model_result")
ONT_EDIT_LABEL = {
    "modify": "修改属性", "create": "创建对象", "delete": "删除对象",
    "link_add": "增加关系", "link_remove": "删除关系",
    # 官方：*"Model results in a Scenario will not be applied to the Ontology"*
    "model_result": "模型预测（不合并）",
}


def _j(v: Any) -> str:
    from decimal import Decimal

    def _default(o: Any) -> Any:
        if isinstance(o, datetime):
            return o.strftime("%Y-%m-%d %H:%M:%S")
        if isinstance(o, Decimal):
            return float(o)
        if isinstance(o, (bytes, bytearray)):
            return o.decode("utf-8", "replace")
        return str(o)

    return json.dumps(v, ensure_ascii=False, default=_default)


def _now() -> str:
    return datetime.now().strftime("%Y-%m-%d %H:%M:%S")


