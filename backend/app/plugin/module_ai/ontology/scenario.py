# 合并 / 丢弃 / 复制 / 过期
# ---------------------------------------------------------------------------
async def apply_scenario(code: str, actor_id: int | None = None,
                         actor_name: str = "") -> dict:
    """合并场景到主本体。

    官方：*"commits all those staged edits to the Ontology as a **single transaction**"*，
    且 *"either all of the Actions will be applied or none of them will be applied if there is
    a validation failure on any of the actions."*

    另：官方明确 **模型结果不会被合并**（它们代表预期结果，不是可改的值）。
    """
    sc = await _check_active(code)
    diff = await scenario_diff(code)
    changes = [c for c in diff["changes"] if c.get("kinds")]
    if not changes:
        return {"ok": False, "msg": "该场景没有任何可合并的编辑"}

    # 合并动作的提交条件 = 谁有权合并（官方：由 merge action 的提交条件管住）
    merge_action = sc.get("merge_action_code") or ""
    if merge_action:
        act = await _svc._find_action(merge_action)
        if not act:
            return {"ok": False, "msg": f"合并动作 {merge_action} 不存在"}
        ctx = await _svc._actor_context(actor_id, actor_name)
        ctx.is_scenario = False   # 合并本身是对主本体的操作
        crit = _svc._ae.evaluate_criteria(act.get("submission_criteria"), ctx, {}, None)
        if not crit["ok"]:
            return {"ok": False, "blocked_by": "submission_criteria",
                    "msg": "不满足合并动作的提交条件：" + "；".join(crit["failures"])}

    # 单事务：全成或全不成
    applied, failed = 0, ""
    try:
        async with _svc.async_db_session.begin() as db:
            for ch in changes:
                meta = await _svc._instance_meta(ch["object_code"])
                if not meta or meta.get("error") or not meta.get("materialized"):
                    failed = f"{ch['object_code']} 未物化，无法合并"
                    raise RuntimeError(failed)
                table = _svc._safe_ident(meta["table"])
                kc = _svc._safe_ident(meta["key_prop"])
                if ch.get("deleted"):
                    await db.execute(
                        _svc._t(f'DELETE FROM "{table}" WHERE {_svc._cast_text(chr(34) + kc + chr(34))} = :k'),
                        {"k": str(ch["object_key"])})
                    applied += 1
                    continue
                changed = ch.get("changed") or {}
                if not changed:
                    continue
                sets = ", ".join(f'"{_svc._safe_ident(c)}" = :{c}' for c in changed)
                res = await db.execute(
                    _svc._t(f'UPDATE "{table}" SET {sets} WHERE {_svc._cast_text(chr(34) + kc + chr(34))} = :__k'),
                    {**{c: changed[c]["after"] for c in changed}, "__k": str(ch["object_key"])})
                if not (res.rowcount or 0):
                    # 基线里没有 → 当作新建
                    cols = ", ".join(f'"{_svc._safe_ident(c)}"' for c in changed)
                    ph = ", ".join(f":{c}" for c in changed)
                    await db.execute(
                        _svc._t(f'INSERT INTO "{table}" ({cols}) VALUES ({ph})'),
                        {c: changed[c]["after"] for c in changed})
                applied += 1
    except Exception as e:  # noqa: BLE001
        await _svc._log_change("", "scenario", "apply_failed",
                               f"场景 {code} 合并失败：{str(e)[:160]}")
        return {"ok": False, "msg": f"合并失败，已回滚（单事务）：{failed or str(e)[:160]}"}

    await _svc._exec_write(
        "UPDATE ai_ont_scenario SET status='applied', applied_at=now(), applied_by=:by "
        "WHERE code=:c", {"by": actor_name or str(actor_id or ""), "c": code})
    await _svc._log_change("", "scenario", "apply",
                           f"场景 {code} 已合并：{applied} 个对象")
    skipped = len(diff.get("model_results") or [])
    return {"ok": True, "objects_applied": applied, "model_results_skipped": skipped,
            "msg": f"已合并 {applied} 个对象到主本体"
                   + (f"（跳过 {skipped} 条模型预测，官方语义不合并）" if skipped else "")}


async def discard_scenario(code: str, actor_name: str = "") -> dict:
    sc = await get_scenario(code)
    if not sc:
        return {"ok": False, "msg": "场景不存在"}
    if sc["status"] != "active":
        return {"ok": False, "msg": f"场景状态为「{sc['status_label']}」"}
    await _svc._exec_write("UPDATE ai_ont_scenario SET status='discarded' WHERE code=:c",
                           {"c": code})
    await _svc._log_change("", "scenario", "discard", f"场景 {code} 已丢弃")
    return {"ok": True, "msg": f"场景已丢弃（{sc['edit_count']} 处编辑未生效）"}


async def duplicate_scenario(code: str, new_name: str = "",
                             actor_name: str = "") -> dict:
    """复制场景（官方：*"You can also duplicate a Scenario along with its existing Actions
    and parameters"*）。"""
    sc = await get_scenario(code)
    if not sc:
        return {"ok": False, "msg": "场景不存在"}
    name = new_name or f"{sc['name']}（副本）"
    r = await create_scenario({
        "name": name, "description": sc["description"],
        "merge_action_code": sc["merge_action_code"], "scope": sc["scope"],
        "created_by": actor_name,
    }, actor_name)
    new_code = r["code"]
    for e in await list_edits(code):
        await _svc._exec_write(
            "INSERT INTO ai_ont_scenario_edit(scenario_code,object_code,object_key,kind,"
            "before,after,action_code) VALUES (:sc,:oc,:ok,:k,:b,:a,:ac)",
            {"sc": new_code, "oc": e["object_code"], "ok": e["object_key"], "k": e["kind"],
             "b": _j(e["before"]), "a": _j(e["after"]), "ac": e["action_code"]})
    n = await _count_edits(new_code)
    await _svc._exec_write(
        "UPDATE ai_ont_scenario SET edit_count=:n, action_codes=:ac WHERE code=:c",
        {"n": n, "ac": _j(sc["action_codes"]), "c": new_code})
    return {"ok": True, "code": new_code, "msg": f"已复制为「{name}」"}


async def remove_scenario(code: str) -> dict:
    await _svc._exec_write("UPDATE ai_ont_scenario SET is_deleted=true WHERE code=:c",
                           {"c": code})
    await _svc._exec_write("DELETE FROM ai_ont_scenario_edit WHERE scenario_code=:c",
                           {"c": code})
    return {"ok": True, "msg": "场景已删除"}


async def expire_scenarios() -> dict:
    """TTL 清理：超过寿命的场景自动过期并删掉其编辑（官方默认 31 天）。"""
    rows = (await _svc._exec(
        "SELECT code FROM ai_ont_scenario WHERE is_deleted=false AND status='active' "
        "AND expires_at IS NOT NULL AND expires_at < now()", {})).fetchall()
    codes = [r[0] for r in rows]
    for c in codes:
        await _svc._exec_write(
            "UPDATE ai_ont_scenario SET status='expired' WHERE code=:c", {"c": c})
        await _svc._exec_write("DELETE FROM ai_ont_scenario_edit WHERE scenario_code=:c",
                               {"c": c})
    return {"ok": True, "expired": len(codes), "codes": codes,
            "msg": f"已过期 {len(codes)} 个场景"}


